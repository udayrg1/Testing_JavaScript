let x : boolean = false;  // here x value is false

if ( x = true) { // however here we assigned true value using "=" then if condition passed (i.e., true)

    console.log("Hello Uday") // since if is true, this line will execute to print
}

/*Execution flow

Initially, x = false.

Inside the if condition, x = true assigns true to x.

The assignment expression evaluates to true.

Therefore, the if block executes.

The output is Hello Uday.

The final value of x is true.*/