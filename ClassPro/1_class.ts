/* 

CLASS - A class is a blueprint or template that defines the properties, methods and constructor 
                                                      used to create objects.

Syntax:

class ClassName{
        //methods, variables, constructors and objects
}

METHOD: A method is  a function which is defined inside a class that represents an action or behavior 
                                                    performed by the class. 

Syntax:

class ClassName{
    methodName(): void{
        //statement to execute
    }
}

OBJECT: An object is an instance of a class. It is created using the new keyword and can access the properties
                                                    and methods defined by that class

CLASS --> Blue print
Object --> ACtual instance created from that blueprint

Syntax: let objectName = new ClassName();

let -> Decalres a variable/ variable declaration
objectName -> variable that hold the object reference
= -> assignment operator
new -> creates a new object(intance)/ keyword
ClassName -> name of the class
() -> calls the construtor
ClassName() -> constructor
new ClassName() -> object
*/